<?php

namespace Tests\Feature;

use App\Models\Cliente;
use App\Models\Declaracion;
use App\Models\Pago;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class IntegrityAndPaymentTest extends TestCase
{
    use RefreshDatabase;

    public function test_siguiente_numero_declaracion_returns_autogenerated_code(): void
    {
        $user = User::factory()->create();
        $this->actingAs($user);

        $response = $this->getJson('/api/declaraciones/siguiente-numero');

        $response->assertOk()
            ->assertJsonPath('success', true)
            ->assertJsonPath('data.numero_declaracion', 'DA-001');
    }

    public function test_creating_declaration_with_overpay_fails(): void
    {
        $user = User::factory()->create();
        $this->actingAs($user);

        $client = Cliente::create([
            'nombres' => 'Pedro',
            'apellidos' => 'Picapiedra',
            'cedula' => '0923456784',
            'email' => 'pedro@example.test',
            'activo' => true,
        ]);

        $response = $this->postJson('/api/declaraciones/con-pago', [
            'cliente_id' => $client->id,
            'numero_declaracion' => 'DA-999',
            'tipo' => 'Importacion',
            'valor_mercancia' => 1000,
            'monto' => 5000, // Sobrepago inválido
            'metodo_pago' => 'transferencia',
            'estado' => 'pagado',
        ]);

        $response->assertStatus(422)
            ->assertJsonPath('success', false)
            ->assertJsonValidationErrors(['monto']);
    }

    public function test_can_register_additional_payment_to_pending_declaration(): void
    {
        $user = User::factory()->create(['role' => 'operador']);
        $this->actingAs($user);

        $client = Cliente::create([
            'nombres' => 'Vilma',
            'apellidos' => 'Picapiedra',
            'cedula' => '0923456784',
            'email' => 'vilma@example.test',
            'activo' => true,
        ]);

        $declaracion = Declaracion::create([
            'cliente_id' => $client->id,
            'numero_declaracion' => 'DA-100',
            'tipo' => 'Importacion',
            'valor_mercancia' => 2000,
            'estado' => 'pendiente',
            'fecha_declaracion' => now()->toDateString(),
        ]);

        Pago::create([
            'declaracion_id' => $declaracion->id,
            'monto' => 1000,
            'metodo_pago' => 'transferencia',
            'estado' => 'pagado',
            'fecha_pago' => now(),
        ]);

        // Registrar abono final de $1000
        $response = $this->postJson("/api/declaraciones/{$declaracion->id}/pagos", [
            'monto' => 1000,
            'metodo_pago' => 'transferencia',
            'estado' => 'pagado',
        ]);

        $response->assertStatus(201)
            ->assertJsonPath('success', true)
            ->assertJsonPath('data.declaracion.estado', 'pagado');

        $this->assertEquals('pagado', $declaracion->fresh()->estadoVisible());
    }

    public function test_additional_payment_exceeding_remaining_balance_fails(): void
    {
        $user = User::factory()->create(['role' => 'operador']);
        $this->actingAs($user);

        $client = Cliente::create([
            'nombres' => 'Pablo',
            'apellidos' => 'Mármol',
            'cedula' => '0923456784',
            'email' => 'pablo@example.test',
            'activo' => true,
        ]);

        $declaracion = Declaracion::create([
            'cliente_id' => $client->id,
            'numero_declaracion' => 'DA-101',
            'tipo' => 'Importacion',
            'valor_mercancia' => 2000,
            'estado' => 'pendiente',
            'fecha_declaracion' => now()->toDateString(),
        ]);

        Pago::create([
            'declaracion_id' => $declaracion->id,
            'monto' => 1500,
            'metodo_pago' => 'transferencia',
            'estado' => 'pagado',
            'fecha_pago' => now(),
        ]);

        // Saldo pendiente es 500, se intenta pagar 600
        $response = $this->postJson("/api/declaraciones/{$declaracion->id}/pagos", [
            'monto' => 600,
            'metodo_pago' => 'transferencia',
            'estado' => 'pagado',
        ]);

        $response->assertStatus(422)
            ->assertJsonValidationErrors(['monto']);
    }

    public function test_cannot_delete_client_with_declarations(): void
    {
        $user = User::factory()->create();
        $this->actingAs($user);

        $client = Cliente::create([
            'nombres' => 'Betty',
            'apellidos' => 'Mármol',
            'cedula' => '0923456784',
            'email' => 'betty@example.test',
            'activo' => true,
        ]);

        Declaracion::create([
            'cliente_id' => $client->id,
            'numero_declaracion' => 'DA-102',
            'tipo' => 'Importacion',
            'valor_mercancia' => 500,
            'estado' => 'pendiente',
            'fecha_declaracion' => now()->toDateString(),
        ]);

        $response = $this->deleteJson("/api/clientes/{$client->id}");

        $response->assertStatus(400)
            ->assertJsonPath('success', false);

        $this->assertDatabaseHas('clientes', ['id' => $client->id]);
    }

    public function test_pagos_index_returns_paginated_list(): void
    {
        $user = User::factory()->create();
        $this->actingAs($user);

        $client = Cliente::create([
            'nombres' => 'Bambam',
            'apellidos' => 'Mármol',
            'cedula' => '0923456785',
            'email' => 'bambam@example.test',
            'activo' => true,
        ]);

        $declaracion = Declaracion::create([
            'cliente_id' => $client->id,
            'numero_declaracion' => 'DA-200',
            'tipo' => 'Importacion',
            'valor_mercancia' => 1000,
            'estado' => 'pagado',
            'fecha_declaracion' => now()->toDateString(),
        ]);

        Pago::create([
            'declaracion_id' => $declaracion->id,
            'monto' => 1000,
            'metodo_pago' => 'efectivo',
            'estado' => 'pagado',
            'fecha_pago' => now(),
        ]);

        $response = $this->getJson('/api/pagos?page=1&per_page=10');

        $response->assertOk()
            ->assertJsonPath('current_page', 1)
            ->assertJsonPath('total', 1)
            ->assertJsonPath('data.0.metodo_pago', 'efectivo');
    }
}
